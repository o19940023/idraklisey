/// One navigable web-parity module.
class ModuleEntry {
  const ModuleEntry({
    required this.title,
    required this.icon,
    required this.endpoint,
    this.permission,
    this.anyOf,
    this.group = 'Ümumi',
    this.query = const {},
    this.titleKeys = const ['full_name', 'name', 'title', 'subject', 'student', 'code'],
    this.subtitleKeys = const ['class_name', 'position', 'category', 'email', 'author'],
    this.badgeKey = 'status',
    this.emptyText = 'Məlumat tapılmadı.',
    this.isDataView = false,
    this.customBuilder,
  });

  final String title;
  final IconData icon;
  final String endpoint;
  final String? permission;
  final List<String>? anyOf;
  final String group;
  final Map<String, dynamic> query;
  final List<String> titleKeys;
  final List<String> subtitleKeys;
  final String badgeKey;
  final String emptyText;

  /// For endpoints returning an object or a non-paginated list.
  final bool isDataView;

  final WidgetBuilder? customBuilder;
}

